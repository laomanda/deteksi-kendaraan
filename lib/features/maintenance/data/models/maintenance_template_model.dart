/// Model representasi data dari tabel Supabase 'maintenance_templates'
class MaintenanceTemplateModel {
  final String id;
  final String categoryId;
  final String componentKey;
  final String componentName;
  final String description;
  final int intervalKm;
  final int intervalMonth;
  final int estimatedCostMin;
  final int estimatedCostMax;
  final int priority;
  final DateTime? createdAt;

  const MaintenanceTemplateModel({
    required this.id,
    required this.categoryId,
    required this.componentKey,
    required this.componentName,
    required this.description,
    required this.intervalKm,
    required this.intervalMonth,
    this.estimatedCostMin = 0,
    this.estimatedCostMax = 0,
    this.priority = 1,
    this.createdAt,
  });

  String get itemKey => componentKey;
  String get name => componentName;
  int get intervalMonths => intervalMonth;

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'category_id': categoryId,
      'component_key': componentKey,
      'component_name': componentName,
      'description': description,
      'interval_km': intervalKm,
      'interval_month': intervalMonth,
      'estimated_cost_min': estimatedCostMin,
      'estimated_cost_max': estimatedCostMax,
      'priority': priority,
      if (createdAt != null) 'created_at': createdAt!.toIso8601String(),
    };
  }

  factory MaintenanceTemplateModel.fromJson(Map<String, dynamic> json) {
    return MaintenanceTemplateModel(
      id: json['id'] as String,
      categoryId: json['category_id'] as String? ?? json['categoryId'] as String? ?? '',
      componentKey: json['component_key'] as String? ?? json['componentKey'] as String? ?? '',
      componentName: json['component_name'] as String? ?? json['componentName'] as String? ?? '',
      description: json['description'] as String? ?? '',
      intervalKm: (json['interval_km'] as num?)?.toInt() ?? (json['intervalKm'] as num?)?.toInt() ?? 0,
      intervalMonth: (json['interval_month'] as num?)?.toInt() ?? (json['intervalMonth'] as num?)?.toInt() ?? 0,
      estimatedCostMin: (json['estimated_cost_min'] as num?)?.toInt() ?? 0,
      estimatedCostMax: (json['estimated_cost_max'] as num?)?.toInt() ?? 0,
      priority: (json['priority'] as num?)?.toInt() ?? 1,
      createdAt: json['created_at'] != null
          ? DateTime.tryParse(json['created_at'].toString())
          : null,
    );
  }

