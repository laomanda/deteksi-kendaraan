  static List<MaintenanceTemplateModel> getTemplatesForCategory(String categoryId) {
    final list = defaultTemplates.where((t) => t.categoryId == categoryId).toList();
    if (list.isNotEmpty) return list;
    // Fallback if unknown
    if (categoryId.startsWith('scooter') || categoryId.contains('motorcycle')) {
      return defaultTemplates.where((t) => t.categoryId == 'scooter_cvt').toList();
    }
    return defaultTemplates.where((t) => t.categoryId == 'car_automatic').toList();
  }
